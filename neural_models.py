import torch, torch.nn as nn

torch.manual_seed(0)                                   # reproducibility

X = torch.tensor([[0.,0.],[0.,1.],[1.,0.],[1.,1.]])    # full XOR dataset
y = torch.tensor([[0.],[1.],[1.],[0.]])

model = nn.Sequential(nn.Linear(2, 2), nn.Tanh(), nn.Linear(2, 1))  # 2-2-1, tanh hidden, logit output
loss_fn = nn.BCEWithLogitsLoss()                       # sigmoid + BCE, numerically stable
opt = torch.optim.Adam(model.parameters(), lr=0.05)

for step in range(3000):                               # full-batch training
    opt.zero_grad()
    loss = loss_fn(model(X), y)
    loss.backward()
    if step == 0:
        print("Step-0 grad of hidden weight (2x2):\n", model[0].weight.grad)
    opt.step()

# final gradient at trained weights
opt.zero_grad()
loss = loss_fn(model(X), y)
loss.backward()

with torch.no_grad():
    probs = torch.sigmoid(model(X))
print("Final loss:", loss.item())
print("Probabilities:", probs.squeeze().tolist())
print("Labels (p>0.5):", (probs > 0.5).int().squeeze().tolist())
print("Final grad of hidden weight (2x2):\n", model[0].weight.grad)